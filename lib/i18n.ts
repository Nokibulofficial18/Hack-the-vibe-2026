export type TranslationVars = Record<string, string | number>;

export interface LanguageContextValue {
  lang: Language;
  isBangla: boolean;
  setLang: (next: Language) => void;
  toggleLang: () => void;
  t: (key: TranslationKey, vars?: TranslationVars) => string;
  translateStatus: (status: string) => string;
  translateMetric: (metricType: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

function applyHtmlLang(next: Language) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = next;
  document.documentElement.classList.toggle("lang-bn", next === "bn");
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>("en");

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(LANG_STORAGE_KEY);
      if (saved === "bn" || saved === "en") {
        setLangState(saved);
        applyHtmlLang(saved);
      }
    } catch {
      // ignore storage errors
    }
  }, []);

  const setLang = useCallback((next: Language) => {
    setLangState(next);
    try {
      window.localStorage.setItem(LANG_STORAGE_KEY, next);
    } catch {
      // ignore storage errors
    }
    applyHtmlLang(next);
  }, []);

  const toggleLang = useCallback(() => {
    setLang(lang === "en" ? "bn" : "en");
  }, [lang, setLang]);

  const t = useCallback(
    (key: TranslationKey, vars?: TranslationVars): string => {
      let text: string = TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key];
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
        }
      }
      return text;
    },
    [lang]
  );

  const translateStatus = useCallback(
    (status: string): string => STATUS_LABELS[lang][status] ?? status,
    [lang]
  );

  const translateMetric = useCallback(
    (metricType: string): string => METRIC_LABELS[lang][metricType] ?? metricType,
    [lang]
  );

  const value = useMemo<LanguageContextValue>(
    () => ({
      lang,
      isBangla: lang === "bn",
      setLang,
      toggleLang,
      t,
      translateStatus,
      translateMetric,
    }),
    [lang, setLang, toggleLang, t, translateStatus, translateMetric]
  );

  return React.createElement(LanguageContext.Provider, { value }, children);
}

export function useTranslation(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error("useTranslation must be used within a LanguageProvider");
  }
  return ctx;
}

export const useLanguage = useTranslation;
